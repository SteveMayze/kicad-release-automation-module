#!/usr/bin/env bash
# Build one ZIP per project listed in a release manifest.
#
# Usage: package_release_artifacts.sh <manifest> <release-label> [<zip-dir>]
#
# For each manifest entry, zips the contents of its output directory into
# "<zip-dir>/<project-id>-gerber-<release-label>.zip" (zip-dir defaults to the
# current directory) and prints the ZIP file name on stdout, one per line.
# Relative output directories in the manifest are resolved against the current
# directory, which must be the repository root.
set -euo pipefail

log() {
  echo "$*" >&2
}

if [[ $# -lt 2 || $# -gt 3 || -z "$1" || -z "$2" ]]; then
  log "Usage: $(basename "$0") <manifest> <release-label> [<zip-dir>]"
  exit 2
fi

MANIFEST="$1"
RELEASE_LABEL="$2"
ZIP_DIR_ARG="${3:-$PWD}"

if [[ ! -f "$MANIFEST" ]]; then
  log "Manifest not found: $MANIFEST"
  exit 1
fi
if [[ ! "$RELEASE_LABEL" =~ ^[A-Za-z0-9._-]+$ ]]; then
  log "Release label must match [A-Za-z0-9._-]+: $RELEASE_LABEL"
  exit 1
fi
if ! command -v zip >/dev/null 2>&1; then
  log "zip is required but was not found."
  exit 1
fi

mkdir -p "$ZIP_DIR_ARG"
ZIP_DIR="$(cd "$ZIP_DIR_ARG" && pwd)"

# One "<project-id><TAB><output-dir>" line per project generated by the run.
ENTRIES="$(python3 - "$MANIFEST" <<'PY'
import json
import re
import sys

with open(sys.argv[1], "r", encoding="utf-8") as handle:
    manifest = json.load(handle)

projects = manifest.get("projects") if isinstance(manifest, dict) else None
if not isinstance(projects, list):
    raise SystemExit("Manifest field 'projects' must be a list.")

for project in projects:
    project_id = project["id"]
    output_dir = project["output_dir"]
    if not re.fullmatch(r"[A-Za-z0-9._-]+", project_id):
        raise SystemExit(f"Invalid project id in manifest: {project_id!r}")
    if "\t" in output_dir or "\n" in output_dir:
        raise SystemExit(f"Invalid output_dir in manifest for {project_id}")
    print(f"{project_id}\t{output_dir}")
PY
)"

COUNT=0
while IFS=$'\t' read -r PROJECT_ID OUTPUT_DIR; do
  if [[ -z "$PROJECT_ID" ]]; then
    continue
  fi
  if [[ ! -d "$OUTPUT_DIR" ]] || [[ -z "$(ls -A "$OUTPUT_DIR")" ]]; then
    log "Output directory for project '$PROJECT_ID' is missing or empty: $OUTPUT_DIR"
    exit 1
  fi

  ZIP_NAME="${PROJECT_ID}-gerber-${RELEASE_LABEL}.zip"
  rm -f "$ZIP_DIR/$ZIP_NAME"
  (
    cd "$OUTPUT_DIR"
    zip -r "$ZIP_DIR/$ZIP_NAME" . >&2
  )
  echo "$ZIP_NAME"
  COUNT=$((COUNT + 1))
done <<< "$ENTRIES"

if [[ "$COUNT" -eq 0 ]]; then
  log "No ZIP files produced."
  exit 1
fi
